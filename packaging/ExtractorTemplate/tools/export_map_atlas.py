"""Render all 80 catalogued selector slots, without executing ROM instructions."""
import argparse
import hashlib
import html
import json
import struct
from pathlib import Path
from inventory_rom import ROM_HASH
from rolo_codec import decode_backward_lz
from rolo_maps import parse_map, render_foreground, long
from rolo_stage2 import png_palette


def export(rom, out):
    if hashlib.sha256(rom).hexdigest() != ROM_HASH:
        raise ValueError('Unexpected ROM revision')
    out.mkdir(parents=True, exist_ok=True)
    banks = {}
    rows = []
    for selector in range(80):
        row = {'selector': selector, 'layers': [], 'errors': []}
        palette = b''.join(rom[long(rom, 0x4b08a+selector*16+i*4):
                                long(rom, 0x4b08a+selector*16+i*4)+32] for i in range(4))
        colors = [tuple(((v >> s) & 7)*255//7 for s in (1, 5, 9))
                  for v in struct.unpack('>64H', palette)]
        foreground = long(rom, 0x4ab1a+selector*8) & 0xffffff
        fgdata = rom[foreground:] if rom[foreground:foreground+3] == b'MAP' else decode_backward_lz(rom, foreground)[0]
        bank = parse_map(fgdata)['bank']
        for layer, source in [('foreground', foreground),
                              ('background', long(rom, 0x4ab1e+selector*8) & 0xffffff)]:
            if selector == 0 and layer == 'background':
                row['errors'].append('World background is generated by A558; no static MAP render')
                continue
            try:
                data = rom[source:] if rom[source:source+3] == b'MAP' else decode_backward_lz(rom, source)[0]
                layout = parse_map(data)
                # Original initialization uses the foreground-selected graphics context for both layers.
                if bank not in banks:
                    banks[bank] = decode_backward_lz(rom, long(rom, 0x4af2a+bank*4))[0]
                if layout['width']*layout['height'] > 16_777_216:
                    name = f'selector-{selector:02d}-{layer}'
                    sections = []
                    for oy in range(0, layout['height'], 1024):
                        for ox in range(0, layout['width'], 2048):
                            w,h = min(2048, layout['width']-ox), min(1024, layout['height']-oy)
                            section = f'{name}-x{ox}-y{oy}.png'
                            pixels = render_foreground(rom, layout, banks[bank], long(rom, 0x4af6e+bank*4),
                                                       long(rom, 0x4afb2+bank*4), (ox,oy,w,h))
                            (out/section).write_bytes(png_palette(w,h,pixels,colors))
                            sections.append({'image': section, 'x': ox, 'y': oy, 'width': w, 'height': h,
                                             'sha256': hashlib.sha256((out/section).read_bytes()).hexdigest()})
                    page = name+'-sections.html'
                    (out/page).write_text('<!doctype html><meta charset="utf-8"><h1>Full map sections</h1>'+''.join(f'<p>({s["x"]}, {s["y"]}) — {s["width"]} × {s["height"]}</p><a href="{s["image"]}"><img style="max-width:100%;image-rendering:pixelated" src="{s["image"]}"></a>' for s in sections),encoding='utf-8')
                    row['layers'].append({'layer':layer,'source':source,'graphics_bank':bank,'map_bank':layout['bank'],
                        'width':layout['width'],'height':layout['height'],'image':page,'thumbnail':sections[0]['image'],
                        'sections':sections,'markers':[r for r in layout['records'] if not r['visual']],
                        'sha256':hashlib.sha256((out/page).read_bytes()).hexdigest()})
                    continue
                pixels = render_foreground(rom, layout, banks[bank],
                                           long(rom, 0x4af6e+bank*4), long(rom, 0x4afb2+bank*4))
                name = f'selector-{selector:02d}-{layer}'
                (out/(name+'.png')).write_bytes(png_palette(layout['width'], layout['height'], pixels, colors))
                step = max(1, (layout['width']+479)//480, (layout['height']+239)//240)
                tw, th = (layout['width']+step-1)//step, (layout['height']+step-1)//step
                thumb = bytes(pixels[y*layout['width']+x] for y in range(0, layout['height'], step)
                              for x in range(0, layout['width'], step))
                (out/(name+'-thumb.png')).write_bytes(png_palette(tw, th, thumb, colors))
                row['layers'].append({'layer': layer, 'source': source, 'graphics_bank': bank,
                    'map_bank': layout['bank'], 'width': layout['width'], 'height': layout['height'],
                    'image': name+'.png', 'thumbnail': name+'-thumb.png',
                    'markers': [r for r in layout['records'] if not r['visual']],
                    'sha256': hashlib.sha256((out/(name+'.png')).read_bytes()).hexdigest()})
            except (ValueError, IndexError, struct.error) as error:
                row['errors'].append(f'{layer} ${source:06X}: {error}')
        rows.append(row)
        print(f"Selector {selector:02d}: {len(row['layers'])} layers, {len(row['errors'])} gaps", flush=True)
    report = {'rom_sha256': ROM_HASH, 'selectors': rows,
        'scope': 'Static artwork atlas; selector slots are not a playable-level count. No actors, priority composition, scrolling or gameplay. Background shared-bank context follows loader; individual scenes still need visual comparison.',
        'counts': {'selector_slots': len(rows), 'rendered_layers': sum(len(r['layers']) for r in rows),
                   'gaps': sum(len(r['errors']) for r in rows)}}
    (out/'manifest.json').write_text(json.dumps(report, indent=2)+'\n', encoding='utf-8')
    cards = []
    for row in rows:
        pictures = ''.join(f'<a href="{p["image"]}"><img src="{p["thumbnail"]}"></a><p>{p["layer"]}: {p["width"]} × {p["height"]}; ROM ${p["source"]:06X}; {len(p["markers"])} markers</p>' for p in row['layers'])
        cards.append(f'<article><h2>Selector {row["selector"]:02d}</h2>{pictures}<p>{html.escape("; ".join(row["errors"]))}</p></article>')
    (out/'index.html').write_text('<!doctype html><meta charset="utf-8"><title>Rolo map atlas</title><style>body{background:#101820;color:#eee;font:16px system-ui;margin:24px}main{display:grid;grid-template-columns:repeat(auto-fit,minmax(490px,1fr));gap:20px}article{background:#202d38;padding:16px}img{max-width:100%;image-rendering:pixelated}a{color:#8cf}</style><h1>Rolo — original ROM map atlas</h1><p>'+html.escape(report['scope'])+'</p><p>'+str(report['counts'])+'</p><main>'+''.join(cards)+'</main>', encoding='utf-8')
    return report


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('rom', type=Path)
    p.add_argument('--out', type=Path, required=True)
    a = p.parse_args()
    print(export(a.rom.read_bytes(), a.out)['counts'])
