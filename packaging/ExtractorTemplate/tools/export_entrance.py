"""Export selected ROM animation data as typed native C++ records."""
import argparse,json,struct
from pathlib import Path
from rolo_extract import font_evidence
from rolo_sprites import frame_record
from romtool import read_rom
PROGRAMS=((0x13ecc,(0,4,60)),(0x13eee,(0,4,60)),(0x13f76,(0,12)),(0x13f54,(0,4)),(0x13f32,(56,)),(0x13f10,(52,)))
OPS={0:'Jump',4:'Repeat',8:'Retire',12:'Delay',40:'RandomDelay',44:'RandomJump',52:'VelocityRate',60:'Hold',64:'SetReturn',68:'Return',116:'Sound'}
OPS.update({16:'RepeatWhileNonzero',20:'RepeatWhileZero',24:'RepeatWhileNonnegative',28:'RepeatWhileNegative',32:'RepeatWhilePositive',36:'RepeatWhileNonpositive',48:'RandomJumpNonzero',56:'WriteByte'})
OPS.update({72:'ClearFreeze',76:'CountedJump',80:'SetSelector',96:'Skip',108:'SetBlink',112:'ClearBlink'})
OPS.update({92:'SpawnInherited',84:'RepeatWhileAirborne',88:'RepeatWhileGrounded',100:'SpawnRandom',104:'RandomHold'})

def export(data,out):
 font_evidence(data);nodes={};programs=[];descriptors={};pending=[]
 for definition,selectors in PROGRAMS:
  table=int.from_bytes(data[definition+18:definition+22],'big')
  for selector in selectors:
   delay=data[table+selector];start=int.from_bytes(data[table+selector+1:table+selector+4],'big')
   programs.append((definition,selector,delay,start));pending.append(start)
 while pending:
  address=pending.pop()
  if address in nodes:continue
  if len(nodes)>4096:raise ValueError('Animation graph limit')
  word=struct.unpack_from('>i',data,address)[0];target=0;parameter=word&65535;next_address=address+4;frame=0
  if word>0:
   op='Frame';frame=word
   # Original zero descriptor is an invisible, zero-contact animation frame.
   # Admit only all18 zero bytes; retain strict geometry for every visible frame.
   descriptors[frame]=dict(graphics=[0,0],offset_x=0,offset_y=0,width=0,height=0,byte_count=0) if data[frame:frame+18]==bytes(18) else frame_record(data,frame)
   pending.append(next_address)
  else:
   command=-(word>>16)
   if command not in OPS:raise ValueError(f'Unsupported control {command} at {address:#x}')
   op=OPS[command]
   if op in ('Jump','RandomJump','RandomJumpNonzero','SetReturn','CountedJump'):
    target=int.from_bytes(data[address+4:address+8],'big');pending.append(target);next_address=address+8
   if op in ('SpawnRandom','SpawnInherited'):
    frame=int.from_bytes(data[address+4:address+8],'big');next_address=address+8;pending.append(next_address)
   if op=='RandomHold':pending.append(next_address)
   if op.startswith('RepeatWhile'):target=address-4;pending.extend((target,next_address))
   if op in ('RandomJump','RandomJumpNonzero','SetReturn','Delay','RandomDelay','VelocityRate','Sound','WriteByte','CountedJump','ClearFreeze','Skip','SetBlink','ClearBlink'):pending.append(next_address)
  nodes[address]=(op,parameter,frame,next_address,target)
 addresses=sorted(nodes);indices={a:i for i,a in enumerate(addresses)};frames=sorted(descriptors);fi={f:i for i,f in enumerate(frames)}
 lines=['// Generated by tools/export_entrance.py from the pinned ROM. No machine code.','#pragma once','#include "core/animation.hpp"','namespace rolo::entrance_data {',f'inline constexpr std::array<Frame, {len(frames)}> frames{{{{']
 for f in frames:
  d=descriptors[f];lines.append(f'  Frame{{0x{f:x},0x{d["graphics"][0]:x},0x{d["graphics"][1]:x},{d["offset_x"]},{d["offset_y"]},{d["width"]},{d["height"]},{d["byte_count"]}}},')
 lines+=['}};',f'inline constexpr std::array<AnimationNode, {len(nodes)}> nodes{{{{']
 for a in addresses:
  op,param,f,n,t=nodes[a];frame_value=f if op in ('SpawnRandom','SpawnInherited') else fi.get(f,0);lines.append(f'  AnimationNode{{AnimationOp::{op},{param},{frame_value},{indices.get(n,-1)},{indices.get(t,-1)},0x{a:x}}},')
 lines+=['}};',f'inline constexpr std::array<AnimationProgram, {len(programs)}> programs{{{{']
 for d,s,delay,start in programs:lines.append(f'  AnimationProgram{{0x{d:x},{s},{delay},{indices[start]}}},')
 lines+=['}};','inline constexpr AnimationData data{frames,nodes,programs};','} // namespace rolo::entrance_data','']
 out.write_text('\n'.join(lines));return {'programs':len(programs),'nodes':len(nodes),'frames':len(frames),'source_sha256':'9478d47cc1883df42f3714ea485aedd71b541274eb45a3aa7c49f4a3518305e9'}
if __name__=='__main__':
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('rom');p.add_argument('--out',required=True);a=p.parse_args();print(json.dumps(export(read_rom(a.rom),Path(a.out))))

